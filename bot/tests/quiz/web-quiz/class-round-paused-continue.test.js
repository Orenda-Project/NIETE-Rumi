'use strict';
/**
 * The class tab's card while a round is paused, and the Urdu round list's name line.
 *  - Paused: the card's one button is "Continue" (jg.round.t_resume) and posts to /resume, so the teacher taps once,
 *    not Start and then Continue; under the paused line it says how to carry on and that the children see nothing
 *    (jg.round.t_paused_how, jg.round.t_paused_kids, lifted byte for byte from the deck).
 *  - Urdu list: each name is a first-strong isolate (U+2068 … U+2069, as jg.who.turn_of), so a Latin name's
 *    initial keeps its full stop on its own side in a right-to-left line ("Bilal T.", never ".Bilal T").
 * Golden: every unpaused card (EN and UR), every English screen and the Urdu child screens are byte-identical to the
 * code before this change: the digests below were taken from it and are never regenerated by the change.
 */
const crypto = require('crypto');
const Page = require('../../../shared/templates/class-round.page');
const deck = require('../../../shared/config/copy.v2.json');

const TOKEN = 'tok-fixed';
const h = (s) => crypto.createHash('sha256').update(s).digest('hex').slice(0, 16);
const rows = [{ pos: 0, name: 'Bilal T.', s: 'done' }, { pos: 1, name: 'Bilal A.', s: 'todo', now: true }, { pos: 2, name: 'Sana', s: 'absent' }, { pos: 3, name: 'Hina', s: 'declined' }, { pos: 4, name: 'Ali', s: 'todo' }];
const PAUSED = { done: 14, total: 31 };
const button = (html) => (html.match(/<button[^>]*>([^<]*)<\/button>/g) || []).map((b) => b.replace(/<[^>]+>/g, ''));
const actions = (html) => (html.match(/action="([^"]*)"/g) || []).map((a) => a.slice(8, -1));

describe('a paused round\'s card: one tap to carry on', () => {
  test('EN: the button reads "Continue" and posts to /resume; no "Start the round"', () => {
    const html = Page.renderCard({ lang: 'en', token: TOKEN, started: true, paused: PAUSED });
    expect(button(html)).toEqual([deck['jg.round.t_resume'].en]);
    expect(button(html)).toEqual(['Continue']);
    expect(actions(html)).toEqual(['/r/tok-fixed/round/resume?lang=en']);
    expect(html).not.toContain('Start the round');
  });

  test('UR: the button reads «جاری رکھیں» and posts to /resume', () => {
    const html = Page.renderCard({ lang: 'ur', token: TOKEN, started: true, paused: PAUSED });
    expect(button(html)).toEqual(['جاری رکھیں']);
    expect(actions(html)).toEqual(['/r/tok-fixed/round/resume?lang=ur']);
    expect(html).not.toContain(deck['jg.round.start'].ur);
  });

  test('the how and the children lines are the deck\'s, byte for byte, under the paused line (EN and UR)', () => {
    for (const lang of ['en', 'ur']) {
      const html = Page.renderCard({ lang, token: TOKEN, started: true, paused: PAUSED });
      const how = deck['jg.round.t_paused_how'][lang];
      const kids = deck['jg.round.t_paused_kids'][lang];
      expect([lang, Page.T[lang].tPausedHow, Page.T[lang].tPausedKids]).toEqual([lang, how, kids]);
      expect(html).toContain(`<p class="muted">${how.replace(/"/g, '&quot;')}</p><p class="muted">${kids}</p>`);
      expect(html.indexOf('cr-paused')).toBeLessThan(html.indexOf(kids));
    }
    expect(deck['jg.round.t_paused_how'].ur).toContain('رہے گی');
  });

  test('the how line names the very button the card shows', () => {
    for (const lang of ['en', 'ur']) {
      const quoted = lang === 'en' ? `"${Page.T.en.tResume}"` : `«${Page.T.ur.tResume}»`;
      expect(Page.T[lang].tPausedHow).toContain(quoted);
    }
  });

  test('the paused card names no child and no round id', () => {
    const html = Page.renderCard({ lang: 'en', token: TOKEN, started: true, paused: PAUSED });
    expect(html).not.toMatch(/Bilal|Sana|Testwala/);
  });
});

describe('the Urdu round list: a name is isolated, its full stop on its own side', () => {
  test('UR: every name on the teacher\'s list is wrapped U+2068 … U+2069', () => {
    const html = Page.renderRound({ mode: 'teacher', rows }, { lang: 'ur', token: TOKEN });
    expect(html).toContain('<span class="nm">⁨Bilal T.⁩</span>');
    expect(html).toContain('<span class="nm">⁨Bilal A.⁩</span>');
    expect(html.match(/<span class="nm">[^<]*<\/span>/g)).toHaveLength(rows.length);
    for (const nm of html.match(/<span class="nm">[^<]*<\/span>/g)) expect(nm).toMatch(/^<span class="nm">⁨[^⁨⁩]+⁩<\/span>$/);
  });

  test('UR: the count is in Urdu digits (paused list too)', () => {
    for (const paused of [false, true]) {
      const html = Page.renderRound({ mode: 'teacher', rows, paused }, { lang: 'ur', token: TOKEN });
      expect(html).toContain('<p class="count">۵ میں سے ۱ مکمل، ۱ غیر حاضر</p>');
    }
  });

  test('EN: the names are as typed (no isolate)', () => {
    const html = Page.renderRound({ mode: 'teacher', rows }, { lang: 'en', token: TOKEN });
    expect(html).toContain('<span class="nm">Bilal T.</span>');
    expect(html).not.toMatch(/[⁨⁩]/);
  });
});

describe('golden: everything else is byte-identical to the code before this change', () => {
  const GOLD = {
    'en/card': '062eadf4ab16beed', 'en/card-started': 'a2cfa5371c6d6112', 'en/card-early': 'f8611e42413debfb',
    'ur/card': '84f94a8ac744b529', 'ur/card-started': '09fc7f579b61d826', 'ur/card-early': 'a7042711ca5f320e',
    'en/round-start': '22ab32200c80d7f0', 'en/round-teacher': 'e247808afdc390e2', 'en/round-teacher-paused': '3757f3f0d387a4da',
    'en/round-child': '7e52a9b8ef15f4bf', 'en/round-handback': 'ef85fd54c2a71926',
    'ur/round-start': 'e0eed15759f68a62', 'ur/round-child': '4b35468e35595ae9', 'ur/round-handback': 'd433a7e1e0cc02ea',
    'en/thanks': '6c1bf8b50ba4f57b', 'ur/thanks': '5ab43ba78b56b7a1',
  };
  test('the unpaused cards, the English screens, the Urdu child screens and the thanks', () => {
    const out = {};
    for (const lang of ['en', 'ur']) {
      out[`${lang}/card`] = h(Page.renderCard({ lang, token: TOKEN }));
      out[`${lang}/card-started`] = h(Page.renderCard({ lang, token: TOKEN, started: true }));
      out[`${lang}/card-early`] = h(Page.renderCard({ lang, token: TOKEN, early: true }));
    }
    for (const v of [{ mode: 'start' }, { mode: 'teacher', rows }, { mode: 'teacher', rows, paused: true }, { mode: 'child', rows: [], current: { name: 'Bilal T.' } }, { mode: 'handback', rows: [] }]) {
      out[`en/round-${v.mode}${v.paused ? '-paused' : ''}`] = h(Page.renderRound(v, { lang: 'en', token: TOKEN, turnHref: '/c/x?lang=en' }));
    }
    for (const v of [{ mode: 'start' }, { mode: 'child', rows: [], current: { name: 'Bilal T.' } }, { mode: 'handback', rows: [] }]) {
      out[`ur/round-${v.mode}`] = h(Page.renderRound(v, { lang: 'ur', token: TOKEN, turnHref: '/c/x?lang=ur' }));
    }
    out['en/thanks'] = h(Page.renderThanks({ lang: 'en' }));
    out['ur/thanks'] = h(Page.renderThanks({ lang: 'ur' }));
    expect(out).toEqual(GOLD);
  });

  test('the Urdu teacher list (class-round-retired-still\'s fixture): only the name isolates are new', () => {
    const T40 = `${'a'.repeat(40)}.${'b'.repeat(22)}`;
    const R = ['Asha', 'Bilal', 'Chanda', 'Dawood', 'Esha'].map((n, i) => ({ pos: i + 1, name: `${n} Testwala`, s: ['done', 'absent', 'declined', 'todo', 'todo'][i], ...(i === 3 ? { now: true } : {}) }));
    const before = { plain: ['9eb049d563b2f4fb', 5675], paused: ['e29181dc4a4692ce', 5366] };   // the page before this change
    for (const [k, paused] of [['plain', false], ['paused', true]]) {
      const html = Page.renderRound({ mode: 'teacher', rows: R, paused }, { lang: 'ur', token: T40 });
      const stripped = html.replace(/[\u2068\u2069]/g, '');
      expect([k, h(stripped), Buffer.byteLength(stripped)]).toEqual([k, ...before[k]]);
      expect((html.match(/\u2068/g) || []).length).toBe(R.length);
    }
  });

  test('not paused (null, or the key absent): the card still offers Start, as before', () => {
    for (const lang of ['en', 'ur']) {
      expect(button(Page.renderCard({ lang, token: TOKEN, started: true, paused: null }))).toEqual([deck['jg.round.start'][lang]]);
    }
  });
});
