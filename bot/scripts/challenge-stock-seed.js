#!/usr/bin/env node
'use strict';
/**
 * The registry rows for the Challenge passage stock: prints an idempotent SQL file that inserts ONE
 * challenge_passages row per file in shared/data/child-test/passages, as `draft`, never released, never reviewed.
 * The Set A pointer files (`v3_ref`) get no INSERT: their reference rows belong to the registry seed, and a draft row
 * from here must never take a reference's place if this file were applied first. A pointer file that carries a title
 * gets one guarded UPDATE that fills a NULL title only (ruling 15).
 * A named person moves a row to reviewed / provisional / calibrated and sets released_at on the database; this
 * script never does. Every file must pass the passage check first, or nothing is printed.
 *
 *   node scripts/challenge-stock-seed.js > database/migrations/web_quiz_challenge_stock_seed.sql
 *
 * Pure: reads the passage files, writes only to stdout. The SQL needs the
 * challenge_passages table from the registry migration; ON CONFLICT DO NOTHING keeps a re-run harmless and never
 * overwrites a row someone has already moved up the ladder.
 */
const fs = require('fs');
const path = require('path');
const Gate = require('../shared/services/child-test/passage-gate');

const PASSAGES = path.join(__dirname, '../shared/data/child-test/passages');
const COLUMNS = ['passage_id', 'lang', 'kind', 'pool', 'band', 'status', 'is_reference', 'released_at', 'tokens', 'sentences',
  'mean_sent_len', 'max_word_len', 'readability', 'readability_list', 'q_reach_1', 'q_reach_2', 'q_n', 'title_en',
  'title_ur', 'source_ref', 'licence', 'reviewer', 'reviewed_at', 'twin_of', 'text_hash', 'bank_version'];

function files(dir = PASSAGES) {
  return fs.readdirSync(dir).filter((f) => f.endsWith('.json')).sort()
    .map((f) => JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8')));
}

function rows(dir = PASSAGES) {
  const all = files(dir);
  const bad = all.map((p) => [p.passage_id, Gate.checkPassage(p).problems]).filter(([, x]) => x.length);
  if (bad.length) throw new Error(`passage check failed: ${JSON.stringify(bad)}`);
  return all.filter((p) => !p.v3_ref).map((p) => {
    const m = Gate.measure(p);
    return {
      passage_id: p.passage_id, lang: p.lang, kind: p.kind, pool: p.pool, band: p.band, status: 'draft',
      is_reference: p.is_reference === true, released_at: null,
      tokens: m.tokens, sentences: m.sentences, mean_sent_len: m.mean_sent_len, max_word_len: m.max_word_len,
      readability: m.readability, readability_list: Gate.BANDS[p.band].list,
      q_reach_1: m.q_reach_1, q_reach_2: m.q_reach_2, q_n: m.q_n,
      title_en: p.title_en || null, title_ur: p.title_ur || null, source_ref: p.source_ref, licence: p.licence,
      reviewer: null, reviewed_at: null, twin_of: p.twin_of || null, text_hash: m.text_hash, bank_version: p.bank_version,
    };
  });
}

/** Titles a Set A pointer file carries (ruling 15): the registry seed inserts those rows with NULL titles. */
function pointerTitles(dir = PASSAGES) {
  const out = [];
  for (const p of files(dir).filter((x) => x.v3_ref)) {
    for (const col of ['title_ur', 'title_en']) if (p[col]) out.push({ passage_id: p.passage_id, col, title: p[col] });
  }
  return out;
}

function lit(v) {
  if (v === null || v === undefined) return 'NULL';
  if (typeof v === 'boolean') return v ? 'true' : 'false';
  if (typeof v === 'number') return String(v);
  return `'${String(v).replace(/'/g, "''")}'`;
}

function buildSql(dir = PASSAGES) {
  const r = rows(dir);
  const out = [
    '-- Challenge passage stock: one draft registry row per passage file (shared/data/child-test/passages);',
    '-- the Set A pointer files are skipped (the registry seed owns those reference rows).',
    '-- GENERATED by bot/scripts/challenge-stock-seed.js; do not edit by hand (a test compares this file to the script).',
    '-- Idempotent: ON CONFLICT DO NOTHING never touches a row already in the table (a reviewed or released row stays).',
    '-- Every row is status draft, released_at NULL, reviewer NULL: a named person signs and releases on the database.',
    '-- Needs the challenge_passages table (registry migration). Apply to sandbox first; staging and prod only on a go.',
    '',
  ];
  for (const x of r) {
    out.push(`INSERT INTO public.challenge_passages (${COLUMNS.join(', ')})`);
    out.push(`VALUES (${COLUMNS.map((c) => lit(x[c])).join(', ')})`);
    out.push('ON CONFLICT (passage_id) DO NOTHING;');
  }
  const t = pointerTitles(dir);
  if (t.length) {
    out.push('');
    out.push('-- Set A pointer titles: fill a NULL title on the reference row the registry seed inserted; never overwrite one.');
    for (const x of t) {
      out.push(`UPDATE public.challenge_passages SET ${x.col} = ${lit(x.title)}, updated_at = now() WHERE passage_id = ${lit(x.passage_id)} AND ${x.col} IS NULL;`);
    }
  }
  return `${out.join('\n')}\n`;
}

if (require.main === module) process.stdout.write(buildSql());

module.exports = { buildSql, rows, pointerTitles, COLUMNS };
