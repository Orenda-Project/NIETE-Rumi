#!/usr/bin/env python3
"""
The light Urdu face (app_settings web_quiz_face_lite): wq-nastaliq-7.woff2 from wq-nastaliq-6.woff2.

The same font with every outline point rounded to a grid of GRID font units (UPM 1000: at 26 px one unit is 0.026 px,
so no point moves more than GRID/2 units, 0.10 px at 26 px). Its cmap, glyph order, advances (hmtx) and layout
tables (GSUB, GPOS, GDEF), OS/2 and line metrics are byte for byte the -6 ones, so every string shapes to the same glyphs at the same places
and no line reflows. Also dropped: the STAT table, the gasp table and the name records above ID 6 (the copyright and
the font's names stay). Brotli packs the rounded outlines ~11% smaller.

    python3 -m pip install fonttools brotli
    python3 dashboard/scripts/face-lite/build.py

Writes dashboard/public/wq/fonts/wq-nastaliq-7.woff2 and dashboard/scripts/face-lite/record.json (checked by
dashboard/tests/web-quiz-face-lite.service.test.js). The name is the version: a new cut is a new number.
"""
import hashlib
import io
import json
import os
import sys

from fontTools.ttLib import TTFont

if os.environ.get('PYTHONHASHSEED') != '0':
    os.execve(sys.executable, [sys.executable] + sys.argv, {**os.environ, 'PYTHONHASHSEED': '0'})

GRID = 8
HERE = os.path.dirname(os.path.abspath(__file__))
FONTS = os.path.abspath(os.path.join(HERE, '..', '..', 'public', 'wq', 'fonts'))
SRC = os.path.join(FONTS, 'wq-nastaliq-6.woff2')
OUT = os.path.join(FONTS, 'wq-nastaliq-7.woff2')
RECORD = os.path.join(HERE, 'record.json')
SAME = ('cmap', 'hmtx', 'GSUB', 'GPOS', 'GDEF', 'OS/2', 'post')
# the line box: hhea's other fields (side-bearing extremes) follow the outlines and no browser lays out with them
LINE = ('ascent', 'descent', 'lineGap', 'advanceWidthMax', 'numberOfHMetrics')


def raw_tables(data):
    f = TTFont(io.BytesIO(data), recalcTimestamp=False)
    f.flavor = None
    b = io.BytesIO()
    f.save(b)
    t = TTFont(io.BytesIO(b.getvalue()), recalcTimestamp=False)
    return {k: t.reader[k] for k in t.reader.keys()}, t


def main():
    src = open(SRC, 'rb').read()
    f = TTFont(io.BytesIO(src), recalcTimestamp=False)
    f['name'].names = [n for n in f['name'].names if n.nameID <= 6]
    for tag in ('STAT', 'gasp'):
        if tag in f:
            del f[tag]
    glyf = f['glyf']
    moved = 0
    for name in f.getGlyphOrder():
        g = glyf[name]
        if g.numberOfContours > 0:
            c = g.coordinates
            for i in range(len(c)):
                x, y = c[i]
                nx, ny = GRID * round(x / GRID), GRID * round(y / GRID)
                moved = max(moved, abs(nx - x), abs(ny - y))
                c[i] = (nx, ny)
            g.recalcBounds(glyf)
    f.flavor = 'woff2'
    out = io.BytesIO()
    f.save(out)
    data = out.getvalue()
    a, ta = raw_tables(src)
    b, tb = raw_tables(data)
    for tag in SAME:
        if a[tag] != b[tag]:
            sys.exit(f'{tag} differs from -6')
    for fld in LINE:
        if getattr(ta['hhea'], fld) != getattr(tb['hhea'], fld):
            sys.exit(f'hhea.{fld} differs from -6')
    if ta['head'].unitsPerEm != tb['head'].unitsPerEm:
        sys.exit('unitsPerEm differs from -6')
    if ta.getGlyphOrder() != tb.getGlyphOrder():
        sys.exit('glyph order differs from -6')
    open(OUT, 'wb').write(data)
    record = {
        'about': 'Generated by dashboard/scripts/face-lite/build.py. Do not edit; rebuild.',
        'source': 'wq-nastaliq-6.woff2',
        'source_sha256': hashlib.sha256(src).hexdigest(),
        'source_bytes': len(src),
        'file': 'wq-nastaliq-7.woff2',
        'sha256': hashlib.sha256(data).hexdigest(),
        'bytes': len(data),
        'grid_units': GRID,
        'max_move_units': moved,
        'units_per_em': tb['head'].unitsPerEm,
        'same_tables': list(SAME),
        'same_hhea': list(LINE),
    }
    with open(RECORD, 'w') as fh:
        json.dump(record, fh, indent=1)
        fh.write('\n')
    print(f'{len(src)} -> {len(data)} B ({100 * (1 - len(data) / len(src)):.1f}% smaller), max move {moved} units')


if __name__ == '__main__':
    main()
